# --- 3. TEXT REPORT GENERATOR ---
def build_text_report(data: dict, filename: str = None):
    print(f"\n{Colors.cyan('[+]')} Building Text Report...")
    if not filename:
        filename = f"{REPORTS_DIR}/report_{get_timestamp()}.txt"
    
    border = "=" * 70
    report = f"""
{border}
    PAREEK SECURITY KIT v{__version__} - SECURITY ASSESSMENT REPORT
{border}
Generated: {get_readable_time()}
Codename:  {__codename__}
Analyst:   PSK User

{border}
    EXECUTIVE SUMMARY
{border}
Total Findings: {len(data)}
Report Type: Security Assessment

{border}
    DETAILED FINDINGS
{border}
"""
    for i, (k, v) in enumerate(data.items(), 1):
        report += f"\n[{i}] {k}\n"
        report += "-" * 70 + "\n"
        if isinstance(v, (list, dict)):
            report += json.dumps(v, indent=4, default=str) + "\n"
        else:
            report += str(v) + "\n"
    
    report += f"\n{border}\n"
    report += "DISCLAIMER: This report is for authorized security testing only.\n"
    report += f"{border}\n"
    
    with open(filename, "w") as f:
        f.write(report)
    print(f"  {Colors.green('[+] Saved:')} {filename}")
    return filename

# --- 4. CSV EXPORT ---
def build_csv_report(data: dict, filename: str = None):
    print(f"\n{Colors.cyan('[+]')} Building CSV Report...")
    if not filename:
        filename = f"{REPORTS_DIR}/report_{get_timestamp()}.csv"
    
    with open(filename, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["Field", "Value", "Data Type", "Timestamp"])
        for k, v in data.items():
            if isinstance(v, (list, dict)):
                val = json.dumps(v, default=str)[:500]
                dtype = "JSON"
            else:
                val = str(v)
                dtype = type(v).__name__
            writer.writerow([k, val, dtype, get_readable_time()])
    
    print(f"  {Colors.green('[+] Saved:')} {filename}")
    return filename

