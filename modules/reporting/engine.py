# --- HELPER FUNCTIONS ---
def get_timestamp():
    return datetime.datetime.now().strftime("%Y%m%d_%H%M%S")

def get_readable_time():
    return datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

# --- 1. JSON REPORT BUILDER ---
def build_json_report(data: dict, filename: str = None):
    print(f"\n{Colors.cyan('[+]')} Building JSON Report...")
    if not filename:
        filename = f"{REPORTS_DIR}/report_{get_timestamp()}.json"
    
    report = {
        "meta": {
            "tool": f"Pareek Security Kit v{__version__}",
            "codename": __codename__,
            "generated_at": get_readable_time(),
            "analyst": "PSK User"
        },
        "data": data
    }
    
    with open(filename, "w") as f:
        json.dump(report, f, indent=4, default=str)
    print(f"  {Colors.green('[+] Saved:')} {filename}")
    return filename

