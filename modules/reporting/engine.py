# --- 7. AUTO SCAN + FULL REPORT ---
def auto_scan_and_report(target: str):
    print(f"\n{Colors.cyan('[+]')} Auto Scan + Full Report: {Colors.bold(target)}")
    print(f"  {Colors.dim('Running all relevant modules and collecting data...')}")
    
    all_data = {
        "target": target,
        "scan_started": get_readable_time(),
        "info_gathering": {},
        "dns_records": {},
        "ssl_info": {},
        "http_headers": {},
    }
    
    # Try each module safely
    try:
        from modules.information_gathering.engine import resolve_dns
        import socket
        d = target.replace("https://", "").replace("http://", "").split("/")[0]
        try:
            ips = socket.gethostbyname_ex(d)
            all_data["info_gathering"] = {"hostname": ips[0], "ips": ips[2]}
            print(f"  {Colors.green('[✓]')} DNS resolved")
        except: pass
    except: pass
    
    try:
        import dns.resolver
        d = target.replace("https://", "").replace("http://", "").split("/")[0]
        for rec in ['A', 'MX', 'NS', 'TXT']:
            try:
                answers = dns.resolver.resolve(d, rec, lifetime=3)
                all_data["dns_records"][rec] = [str(a) for a in answers]
            except: pass
        print(f"  {Colors.green('[✓]')} DNS records collected")
    except: pass
    
    try:
        import requests
        url = target if target.startswith("http") else f"https://{target}"
        resp = requests.get(url, timeout=10, allow_redirects=True)
        all_data["http_headers"] = dict(resp.headers)
        all_data["http_status"] = resp.status_code
        print(f"  {Colors.green('[✓]')} HTTP headers collected")
    except: pass
    
    try:
        import ssl, socket
        d = target.replace("https://", "").replace("http://", "").split("/")[0]
        ctx = ssl.create_default_context()
        with ctx.wrap_socket(socket.socket(), server_hostname=d) as s:
            s.settimeout(10)
            s.connect((d, 443))
            cert = s.getpeercert()
            all_data["ssl_info"] = {
                "issuer": dict(x[0] for x in cert.get('issuer', [])),
                "notAfter": cert.get('notAfter', 'N/A'),
                "notBefore": cert.get('notBefore', 'N/A')
            }
        print(f"  {Colors.green('[✓]')} SSL certificate collected")
    except: pass
    
    all_data["scan_completed"] = get_readable_time()
    
    # Generate all report formats
    print(f"\n  {Colors.magenta('--- Generating Reports ---')}")
    base = target.replace("https://", "").replace("http://", "").replace("/", "_").replace(".", "_")
    ts = get_timestamp()
    build_json_report(all_data, f"{REPORTS_DIR}/{base}_{ts}.json")
    build_html_report(all_data, f"{REPORTS_DIR}/{base}_{ts}.html")
    build_text_report(all_data, f"{REPORTS_DIR}/{base}_{ts}.txt")
    build_csv_report(all_data, f"{REPORTS_DIR}/{base}_{ts}.csv")
    executive_summary(all_data)
    print(f"\n  {Colors.green('[✓] All reports generated successfully!')}")

